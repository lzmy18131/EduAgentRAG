"""RAG 提示词模板模块 — 管理所有 Prompt 模板，不硬编码在业务代码中。

包含：
    1. RAG 最终回答模板
    2. 直接检索提示词
    3. 假设问题检索（HyDE）提示词
    4. 子问题拆解提示词
    5. 回溯问题检索提示词
    6. 意图识别分类提示词
"""


class RAGPrompts:
    """RAG 系统所有提示词模板集中管理。"""

    # ────────── 1. RAG 最终回答模板 ──────────

    @staticmethod
    def rag_answer_prompt() -> str:
        """结合检索上下文 + 用户问题生成最终回答（要求按 [编号] 引用来源）。"""
        return """你是一个专业的AI教育智能助手，帮助用户解答问题。

请根据以下规则回答：
1. 如果提供了上下文信息，请严格基于上下文回答问题
2. 如果没有提供上下文，请根据你的知识回答
3. 回答中凡引用或依据上下文时，必须在相应句末用方括号标注来源编号，如 [1]、[2]，
   编号对应下方"上下文信息"中各段落的编号
4. 如果信息不足以回答，请回复"信息不足，无法回答，请联系人工客服"

上下文信息（每段以 [编号] 开头）：
{context}

用户问题：{question}

回答："""

    # ────────── 2. 四种检索策略提示词 ──────────

    @staticmethod
    def direct_retrieval_prompt() -> str:
        """直接检索：对查询不做改写，直接向量检索。"""
        return """基于以下上下文信息回答问题。

上下文：
{context}

问题：{question}
回答："""

    @staticmethod
    def hyde_prompt() -> str:
        """假设问题检索（HyDE）：先生成假答案再检索。"""
        return """请根据以下问题，假设一个可能的答案。不需要真实准确，只需要模拟答案的风格和关键词。

问题：{question}

假设答案："""

    @staticmethod
    def subquery_prompt() -> str:
        """复杂问题拆解为多个子问题。"""
        return """请将以下复杂问题拆解为2-4个独立的子问题，每个子问题应简洁、具体、可独立检索。
只输出子问题列表，每行一个，不要编号。

原始问题：{question}

子问题："""

    @staticmethod
    def backtrack_prompt() -> str:
        """回溯问题：将复杂问题简化为基础问题。"""
        return """请将以下复杂问题转化为一个或多个更基础、更容易检索的问题。
只输出转化后的问题，不要解释。

原始问题：{question}

基础问题："""

    # ────────── 3. 多轮对话指代消解提示词 ──────────

    @staticmethod
    def coreference_prompt() -> str:
        """多轮对话指代消解：结合历史把当前问题的指代替换为明确实体。"""
        return """你是一个对话改写助手。请结合对话历史，把用户当前问题中的指代词（如"它"、"这个"、"那个"、"上面提到的"）替换为历史中明确提到的内容，输出改写后的问题。

只输出改写后的问题，不要解释，不要回答。若无需改写，直接原样输出当前问题。

对话历史：
{history}

当前问题：{question}

改写后的问题："""

    # ────────── 4. 意图识别分类提示词 ──────────

    @staticmethod
    def intent_classify_prompt() -> str:
        """大模型意图分类（BERT 不置信时的二次判定）。"""
        return """你是一个意图识别分类器。请判断用户输入属于以下哪个类别：
- 知识检索：咨询课程、技术知识、学习方法、就业薪资等（需搜索知识库）
- 工具操作：安装软件、配置环境等
- 流程咨询：报名流程、费用咨询等
- 闲聊/其他：打招呼、无意义对话等

只输出类别名称，不要解释。

用户输入：{question}

类别："""
